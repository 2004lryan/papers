"""统一协议（3.3 节）的候选网格——第三轮，只含第二轮网格边界诊断触发的 SVR 与 1D-CNN。

为什么会有第三轮：协议 B10.1 规定，5 折 × 5 次重复嵌套交叉验证的 25 个外层折中，某方法的选中值过半
落在网格同一端点时，按 grids.py 的规则①~④ 平移网格、登记为第三轮、两轮并列报告。端点按 scikit-learn
拟合时实际使用的数值判定（SVR 的 gamma='scale' 为 1/(特征数×训练集方差)，在 45 各次拟合的训练集上为
2.58~2.645）。第二轮（grids.py）25 个外层折的选中计数见 04outputs/47rebuttal_boundary.csv：

    SVR     gamma   scale×25                    → 最大端 25/25
            C       1 000×24、10 000×1
    1D-CNN  层数    5×25                        → 最大端 25/25，已是结构上限
            学习率  10⁻³×24、3×10⁻⁴×1           → 最大端 24/25
            宽度    32×19、16×6                 → 最大端 19/25
    RF      树数    1 600×13、800×7、400×5      → 最大端 13/25

按规则①~④ 给出的第三轮网格：
  SVR     C∈{100, 1 000, 10 000} × gamma∈{0.1, 1, scale, 10}。删去从未选中的 C=10 与 gamma=10⁻³、10⁻⁴（④），
          scale 落入内部（①），共 12 组（②）。
  1D-CNN  层数 5 × 宽度∈{16, 32, 64, 128} × 学习率∈{3×10⁻⁴, 10⁻³, 3×10⁻³}，丢弃率 0.2、权重衰减 10⁻⁴、
          批量 32、200 轮同第二轮。层数已达结构上限 5（③），删去从未选中的 3 与 4（④）；宽度 32 与
          学习率 10⁻³ 落入内部（①）；共 12 组（②）。学习率上端取 3×10⁻³：45 的内层评分遇 NaN 预测即抛出
          异常、所在分片中断，学习率越大发散的风险越高，而 45 不改动，再扩一档的名额因此给宽度。
  RF 不设第三轮（协议 C3 2026-09-15 第三轮网格行）：第二轮格点缓存上树数 800→1 600 的内层 RMSE 中位变化为
  −0.02%~−0.08%，树数方向已是平台。

怎么用：第三轮在独立工作目录中运行未改动的 45，本文件以 grids.py 之名放进该目录的 02code/，45 的缓存指纹
与来源清单记录的就是本文件的全文与哈希。所以本文件不得 import grids（在工作目录里它自己就叫 grids），
也只定义上面两个方法：误跑其他方法时，45 在取 GRIDS[m] 时即停下。两轮共有的候选（SVR 3 组、1D-CNN 4 组）
与 grids.py 写法逐字相同，45 的缓存键因而可以跨轮比对。本文件的 SHA-256 登记在协议 C3，登记后不得改动。
"""
from typing import Any

GRIDS: dict[str, list[Any]] = {
    'SVR': [(C, g) for C in [100, 1000, 10000] for g in [0.1, 1.0, 'scale', 10.0]],
    '1D-CNN': [dict(w=w, nl=5, lr=lr, dp=0.2, wd=1e-4, bs=32, ep=200)
               for w in [16, 32, 64, 128] for lr in [3e-4, 1e-3, 3e-3]],
}
for _m, _g in GRIDS.items():
    assert len(_g) == 12, (_m, len(_g))

