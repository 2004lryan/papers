    prov = pd.read_excel(RAW / "17-23年新能源汽车保有量.xlsx")
    prov.columns = ["省份", "代码", "年份", "保有量"]
    p23 = prov[prov["年份"] == 2023].set_index("省份")["保有量"]

    city_sum = df.groupby("省份")["保有量"].sum()
    chk = pd.DataFrame({"城市之和": city_sum, "省级表2023": p23}).fillna(0).astype(int)
    chk["差值(省级−城市和)"] = chk["省级表2023"] - chk["城市之和"]
    chk = chk.sort_values("差值(省级−城市和)", key=abs, ascending=False)
    off = chk[chk["差值(省级−城市和)"] != 0]
    logger.info("省级校验：31 省中差值≠0 的 %s 个", len(off))
    print("=== 各省校验（只列差值≠0）===")
    print(off.to_string() if len(off) else "  全部 31 省城市之和 = 省级值")

    # Infer row 293: exactly one province has a non-zero difference, and it lies within [2860, 3186], the values of
    # rows 294 and 292 between which row 293 must fall
    cand = off[(off["差值(省级−城市和)"] >= 2860) & (off["差值(省级−城市和)"] <= 3186)]
    if len(cand) == 1 and len(off) == 1:
        p, v = cand.index[0], int(cand["差值(省级−城市和)"].iloc[0])
        known = set(df.loc[df["省份"] == p, "城市"])
        # The only one of Heilongjiang's 13 prefecture-level divisions that is not in the transcribed table: Mudanjiang
        missing_name = {"黑龙江": "牡丹江市"}.get(p, f"{p}未识别城市")
        df = pd.concat([df, pd.DataFrame([{"序号": 293, "省份": p, "城市": missing_name, "保有量": v,
                                           "来源": "省级差值推断"}])])
        df = df.sort_values("序号").reset_index(drop=True)
        logger.info("推断第 293 行：%s %s %s（省级差值唯一命中区间）", p, missing_name, v)
        print(f"\n推断第 293 行 = {p} {missing_name} {v}"
              f"（该省差值唯一落在 2860–3186 区间；已知该省城市 {len(known)} 个）")
    elif len(off):
        print("\n⚠ 差值省份不止一个或不在缺行区间，存在识别错误，需回看截图")

    out = RAW / "2023各省市新能源汽车保有量（截图识别）.csv"
